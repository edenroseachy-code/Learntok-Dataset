"""**Searching all the topics and collecting unique video IDs**"""

VIDEO_PER_TOPIC = 50

all_video_ids = []
video_categories = {}
video_subcategories = {}

for category, subtopics in search_terms.items():
    for subtopic, term in subtopics.items():
        print("Searching:", category,"-", subtopic)

        videos_found = 0
        next_page_token = None

        while videos_found < VIDEO_PER_TOPIC:
            request = youtube.search().list(
                part="snippet",
                q=term,
                type="video",
                videoDuration="short",
                 relevanceLanguage="en",
                maxResults=50,
                pageToken = next_page_token
            )

            response = request.execute()


            for item in response.get("items", []):

                video_id = item["id"].get("videoId")
                if not video_id:
                    continue

                    #to not add the same video twice

                if video_id not in all_video_ids:
                    all_video_ids.append(video_id)
                    video_categories[video_id] = category
                    video_subcategories[video_id] = subtopic

                    videos_found +=1

                    if videos_found >= VIDEO_PER_TOPIC:
                        break

            next_page_token = response.get("nextPageToken")

            if not next_page_token:
                break


print()
print("Unique videos found:", len(all_video_ids))

"""**Collecting all details from the shorts**"""

all_videos = []

for i in range(0, len(all_video_ids), 50):

    batch_ids = all_video_ids[i:i+50]

    print(
        "Getting videos",
        i + 1,
        "to",
        min(i + 50, len(all_video_ids))
    )

    request = youtube.videos().list(
        part="snippet,statistics,contentDetails",
        id=",".join(batch_ids)
    )

    response = request.execute()

    for video in response["items"]:

        video_id = video["id"]

        all_videos.append({
            "video_id": video_id,
            "educational_topic": video_categories.get(video_id, "Unknown"),
            "educational_subtopic": video_subcategories.get(video_id, "Unknown"),
            "title": video["snippet"]["title"],
            "description": video["snippet"]["description"],
            "channel": video["snippet"]["channelTitle"],
            "published_at": video["snippet"]["publishedAt"],
            "duration": video.get("contentDetails", {}).get("duration"),
            "views": video.get("statistics", {}).get("viewCount", 0),
            "likes": video.get("statistics", {}).get("likeCount", 0),
            "comments": video.get("statistics", {}).get("commentCount", 0)
        })

